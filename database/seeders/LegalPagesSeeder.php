<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Modules\Content\Enums\LegalPageSlug;
use App\Modules\Content\Enums\LegalPageStatus;
use App\Modules\Content\Models\LegalPage;
use Illuminate\Database\Seeder;

/**
 * DEC-051 — مسودات مبدئية مكتوبة من الوثائق نفسها (13، 32، 18، 04، 14، 19) بلا أي وعد خارج القواعد.
 * كلها «مسودة تحتاج مراجعة قانونية» حتى ينشرها المدير العام من اللوحة (OD-04).
 * لا تمس صفحة لها نسخ بالفعل.
 */
final class LegalPagesSeeder extends Seeder
{
    public function run(): void
    {
        $pages = [
            LegalPageSlug::Terms->value => [0, 'الشروط والأحكام', self::terms()],
            LegalPageSlug::Privacy->value => [1, 'سياسة الخصوصية', self::privacy()],
            LegalPageSlug::Cancellation->value => [2, 'سياسة الإلغاء', self::cancellation()],
            LegalPageSlug::Faq->value => [3, 'الأسئلة الشائعة', self::faq()],
        ];

        foreach ($pages as $slug => [$sort, $title, $body]) {
            $page = LegalPage::query()->firstOrCreate(['slug' => $slug], ['title' => $title, 'sort' => $sort]);

            if ($page->versions()->exists()) {
                continue;
            }

            $page->versions()->create([
                'version' => 1,
                'title' => $title,
                'body' => $body,
                'status' => LegalPageStatus::Draft,
                'requires_legal_review' => true,
            ]);
        }
    }

    private static function terms(): string
    {
        return <<<'HTML'
<p>تنظّم هذه الشروط استخدام تطبيق بريمو وخدماته. استخدام التطبيق وإرسال طلب خدمة يعني الموافقة على هذه الشروط وعلى سياسة الإلغاء وسياسة الخصوصية.</p>
<h2>الخدمة</h2>
<p>بريمو منصة لطلب الخدمات المنزلية (سباكة، كهرباء، تكييفات، وغيرها). في المرحلة الحالية يُنفّذ الطلبات فنيون تابعون للمنصة، ويعيّن فريق التشغيل الفني المناسب لكل طلب حسب الفئة والمنطقة والموعد.</p>
<h2>الحساب</h2>
<ul>
<li>التسجيل بالبريد الإلكتروني وكلمة مرور، ويلزم تفعيل البريد قبل إرسال أي طلب.</li>
<li>صاحب الحساب مسؤول عن صحة بياناته وسرية كلمة المرور.</li>
<li>للإدارة إيقاف أو حظر الحساب عند مخالفة هذه الشروط، مع ذكر السبب.</li>
</ul>
<h2>الطلب والموعد</h2>
<ul>
<li>يحدد العميل الخدمة ونوع المشكلة والعنوان والموعد (الآن أو فترة مجدولة)، ويمكنه إضافة وصف وصور وفيديو وتسجيل صوتي.</li>
<li>يمكن تعديل الطلب ما دام بانتظار التعيين.</li>
<li>الحد الأقصى للطلبات المفتوحة في وقت واحد يحدده التطبيق.</li>
</ul>
<h2>المعاينة والسعر</h2>
<ul>
<li>كل طلب يبدأ بزيارة معاينة مجانية في المرحلة الحالية.</li>
<li>بعد المعاينة يقدّم الفني عرض تنفيذ بسعر المصنعية والخامات، ولا يبدأ التنفيذ إلا بعد موافقة العميل من التطبيق.</li>
<li>رفض عرض التنفيذ يُغلق الطلب دون أي مبلغ.</li>
<li>أي تكلفة إضافية أثناء التنفيذ تُعرض كمقترح سعر، ويتوقف البند حتى موافقة العميل، والسعر المتفق عليه أولًا لا يتغير. المقترح الذي لا يُرد عليه خلال المهلة يُعتبر مرفوضًا.</li>
</ul>
<h2>الدفع</h2>
<ul>
<li>الدفع بعد انتهاء التنفيذ فقط، بالمبلغ النهائي الظاهر في التطبيق كاملًا، ولا يوجد دفع جزئي.</li>
<li>طرق الدفع المتاحة تظهر في التطبيق: نقدًا للفني، أو تحويل إنستاباي إلى حساب المنصة يؤكده فريق الإدارة بعد وصول المبلغ.</li>
<li>لا يحفظ التطبيق بيانات البطاقات البنكية.</li>
</ul>
<h2>الإنهاء والتأكيد</h2>
<ul>
<li>بعد الدفع النقدي يؤكد العميل انتهاء الخدمة، وإن لم يؤكد يُغلق الطلب تلقائيًا بعد المدة المحددة في التطبيق.</li>
<li>عند وجود مشكلة يمكن «فتح مشكلة» من التطبيق من وقت وصول الفني وحتى 72 ساعة بعد إغلاق الطلب، وتراجعها الإدارة وتقرر فيها.</li>
<li>الاسترداد، إن تقرر، يكون بقرار الإدارة في المشكلة المفتوحة وللمدفوعات الإلكترونية.</li>
</ul>
<h2>التقييم</h2>
<p>يقيّم العميل الفني والفني العميل مرة واحدة لكل طلب مكتمل خلال المدة المحددة، ولا يمكن تعديل التقييم بعد إرساله. للإدارة إخفاء التقييم المسيء.</p>
<h2>التواصل</h2>
<ul>
<li>المحادثة داخل التطبيق، ويظهر رقم الهاتف للطرفين بعد تأكيد الطلب ولمدة محددة بعد إغلاقه.</li>
<li>ممنوع الاتفاق على تنفيذ خارج المنصة أو إساءة التعامل مع أي طرف.</li>
</ul>
<h2>تعديل الشروط</h2>
<p>عند نشر نسخة جديدة من الشروط يُطلب من العميل الموافقة عليها عند أول طلب بعد سريانها، ويُحفظ رقم النسخة ووقت الموافقة مع كل طلب.</p>
<h2>التواصل مع الدعم</h2>
<p>من «المساعدة والدعم» داخل التطبيق، أو عبر عنوان الدعم الظاهر أسفل هذه الصفحة.</p>
HTML;
    }

    private static function privacy(): string
    {
        return <<<'HTML'
<p>توضح هذه السياسة البيانات التي يجمعها تطبيق بريمو، ومن يراها، وإلى متى تُحفظ.</p>
<h2>البيانات التي نجمعها</h2>
<ul>
<li><strong>الحساب:</strong> الاسم، البريد الإلكتروني، رقم الهاتف، الصورة الشخصية إن أُضيفت. كلمة المرور تُحفظ مشفّرة ولا يمكن قراءتها.</li>
<li><strong>العناوين:</strong> العنوان التفصيلي ونقطة الموقع على الخريطة لتنفيذ الخدمة.</li>
<li><strong>الطلب:</strong> الخدمة ونوع المشكلة والوصف والموعد، والصور والفيديو والتسجيلات الصوتية المرفقة (تُزال بيانات الموقع المضمنة في الصور).</li>
<li><strong>المحادثات:</strong> نص الرسائل والصور المرسلة داخل التطبيق.</li>
<li><strong>الدفع:</strong> المبالغ وطريقة الدفع ومراجع العمليات فقط. عند تحويل إنستاباي: الرقم المرجعي للتحويل وصورة الإيصال إن أُرفقت. لا تُحفظ بيانات البطاقات.</li>
<li><strong>التقييمات</strong> التي يكتبها الطرفان.</li>
<li><strong>للفنيين:</strong> مستندات الهوية والصورة (تخزين خاص للإدارة فقط)، وبيانات استلام المستحقات (مشفّرة)، وموقع الفني أثناء التوجه للعميل فقط.</li>
</ul>
<h2>الموقع</h2>
<ul>
<li>يُرسل موقع الفني كل 30 ثانية تقريبًا أثناء حالة «في الطريق» فقط، ويراه العميل صاحب الطلب وحده.</li>
<li>نقاط المسار تُحذف عند إغلاق الطلب أو إلغائه. نقطة الوصول تُحفظ 90 يومًا لحل أي خلاف.</li>
</ul>
<h2>من يرى البيانات</h2>
<ul>
<li><strong>قبل تأكيد الطلب</strong> لا يرى الفني العنوان التفصيلي ولا الهاتف، بل اسم المنطقة فقط.</li>
<li><strong>بعد التأكيد</strong> يرى الفني المعيَّن العنوان التفصيلي، ويظهر رقم الهاتف للطرفين حتى 24 ساعة بعد الإغلاق.</li>
<li>في المحادثة قبل التأكيد تُحجب الأرقام والروابط والبريد تلقائيًا، ويُحفظ النص الأصلي مشفّرًا ولا تفتحه الإدارة إلا عند مشكلة أو بلاغ.</li>
<li><strong>رابط مشاركة الزيارة</strong> يعرض اسم الفني الأول وحالة الطلب فقط، بلا عنوان ولا خريطة ولا هاتف ولا سعر، وينتهي بانتهاء الطلب.</li>
<li><strong>فريق الإدارة</strong> يرى ما يلزم للتشغيل وحل المشكلات، والإجراءات المالية للمدير العام فقط.</li>
</ul>
<h2>مدد الاحتفاظ</h2>
<ul>
<li>الوسائط المؤقتة غير المرفقة بطلب: 24 ساعة.</li>
<li>نقطة الوصول: 90 يومًا.</li>
<li>مستندات هوية الفني المرفوض: 90 يومًا بعد الرفض النهائي ثم تُحذف.</li>
<li>الطلبات والأحداث والمدفوعات: تُحفظ دائمًا، وتصبح مجهولة الهوية عند حذف الحساب.</li>
</ul>
<h2>حذف الحساب</h2>
<p>يمكن حذف الحساب من «حسابي» داخل التطبيق ما لم يوجد طلب نشط. عند الحذف تُزال بيانات الحساب الشخصية، وتبقى سجلات الطلبات والمدفوعات مجهولة الهوية.</p>
<h2>البريد والإشعارات</h2>
<p>يُستخدم البريد للتفعيل واستعادة كلمة المرور والإشعارات المهمة للطلب، والإشعارات داخل التطبيق لمتابعة الطلب.</p>
<h2>التواصل</h2>
<p>لأي استفسار عن البيانات: عبر «المساعدة والدعم» أو عنوان الدعم أسفل هذه الصفحة.</p>
HTML;
    }

    private static function cancellation(): string
    {
        return <<<'HTML'
<p>لا توجد رسوم ولا غرامات على الإلغاء. كل إلغاء يُسجَّل مع سببه ووقته.</p>
<h2>إلغاء العميل</h2>
<ul>
<li>الإلغاء مجاني مع ذكر السبب ما دام الطلب بانتظار التعيين، أو مؤكدًا، أو الفني في الطريق.</li>
<li>بعد وصول الفني لا يُلغى الطلب من التطبيق؛ عند وجود مشكلة يُستخدم «فتح مشكلة» وتراجعها الإدارة.</li>
<li>رفض عرض التنفيذ بعد المعاينة المجانية ليس إلغاءً، ويُغلق الطلب دون أي مبلغ.</li>
<li>بعد انتهاء التنفيذ لا يوجد إلغاء؛ يمكن فتح مشكلة حتى 72 ساعة بعد إغلاق الطلب.</li>
</ul>
<h2>اعتذار الفني أو تعذّر التنفيذ</h2>
<ul>
<li>إذا اعتذر الفني قبل الوصول يعود الطلب لتعيين فني آخر دون أي إجراء من العميل.</li>
<li>بعد الوصول يمكن للفني الإبلاغ عن تعذّر التنفيذ، أو عن عدم وجود العميل بعد مدة الانتظار المحددة، ويُلغى الطلب دون أي مبلغ.</li>
</ul>
<h2>إلغاء الإدارة</h2>
<p>للإدارة إلغاء الطلب لأسباب تشغيلية مع ذكر السبب، ويصل إشعار بذلك.</p>
HTML;
    }

    private static function faq(): string
    {
        return <<<'HTML'
<h3>كيف أتابع حالة طلبي؟</h3>
<p>من «طلباتي» ثم اختيار الطلب لعرض حالته والخطوات المتاحة.</p>
<h3>هل المعاينة مجانية؟</h3>
<p>نعم في المرحلة الحالية. بعد المعاينة يظهر عرض التنفيذ للموافقة أو الرفض، والرفض يُغلق الطلب دون أي مبلغ.</p>
<h3>كيف يتم الدفع؟</h3>
<p>بعد انتهاء التنفيذ: نقدًا للفني أو تحويل إنستاباي إلى حساب المنصة، ويؤكد فريق الإدارة وصول التحويل قبل إغلاق الطلب.</p>
<h3>متى يمكن إلغاء الطلب؟</h3>
<p>مجانًا قبل وصول الفني. بعد الوصول يُستخدم «فتح مشكلة».</p>
<h3>كيف أفتح مشكلة؟</h3>
<p>من تفاصيل الطلب عند ظهور «فتح مشكلة»، حتى 72 ساعة بعد الإغلاق.</p>
HTML;
    }
